function trimCuts(db2, s, keep = []) {
  const cuts = [], n = db2.length;
  let k = 0;
  while (k < n) {
    if (db2[k] < s.thr) {
      let m = k;
      while (m < n && db2[m] < s.thr) m++;
      const L = (m - k) * TRIM_FRAME;
      if (k > 0 && m < n && L * 1e3 >= s.minMs && !keep.some(([a, b]) => a < m * TRIM_FRAME && b > k * TRIM_FRAME)) {
        const rem = Math.min(Math.max(L * s.amount / 100, s.maxMs ? L - s.maxMs / 1e3 : 0), L - 2 * TRIM_TAIL);
        if (rem >= 0.03) {
          const mid = (k + m) * TRIM_FRAME / 2;
          cuts.push([mid - rem / 2, mid + rem / 2]);
        }
      }
      k = m;
    } else k++;
  }
  return cuts;
}
